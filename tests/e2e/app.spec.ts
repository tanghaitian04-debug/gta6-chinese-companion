test('完整备份、无效文件和恢复确认',async({page})=>{
  await visit(page,'me')
  const imported=page.getByLabel('导入 JSON 备份')
  await imported.setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{}')})
  await expect(page.getByText('无法导入。文件不是有效备份或超过 4 MB。')).toBeVisible()
  const data={version:1,active:'test-save',profiles:[{id:'test-save',name:'测试恢复档',items:{},checks:[]}]}
  await imported.setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))})
  await page.getByRole('button',{name:'确认恢复备份'}).click()
  await expect(page.getByRole('combobox',{name:'当前存档'})).toHaveValue('test-save')
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出 JSON'}).click()
  expect((await download).suggestedFilename()).toBe('leonida-companion-backup.json')
  await page.reload()
  await expect(page.getByRole('combobox',{name:'当前存档'})).toHaveValue('test-save')
})

