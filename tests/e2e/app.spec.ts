import {test,expect,type Page} from '@playwright/test'

const visit=(page:Page,route='')=>page.goto('./#/'+route)

test('首页、资源、手机布局与中文 / 拼音搜索',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  const response=await visit(page)
  expect(response?.ok()).toBeTruthy()
  await expect(page.getByRole('heading',{level:1})).toHaveText(/中文.*全能助手/)
  await expect.poll(()=>page.locator('.hero-map').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(100)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  await page.getByRole('button',{name:'全站搜索',exact:true}).click()
  const field=page.getByRole('textbox',{name:'全站关键词'})
  await field.fill('jichang')
  await page.getByRole('button',{name:/罪恶城国际机场/}).first().click()
  await expect(page.getByTestId('place-detail').getByRole('heading',{name:'罪恶城国际机场'})).toBeVisible()
  await expect(page.getByTestId('place-detail').getByText('大致区域')).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('place-detail')).toBeVisible()
  expect(errors).toEqual([])
})

test('地图底图、瓦片、缩放、点选、分类与无效分享地址',async({page})=>{
  await visit(page,'map')
  const canvas=page.getByTestId('map-canvas')
  await expect(canvas).toBeVisible()
  await expect.poll(()=>canvas.locator('img.leaflet-image-layer').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(500)
  if(await page.getByRole('button',{name:'筛选',exact:true}).isVisible())await page.getByRole('button',{name:'筛选',exact:true}).click()
  await page.getByRole('button',{name:'收集品',exact:true}).click()
  await expect(page.getByRole('checkbox',{name:'显示待核验地点'})).not.toBeChecked()
  await page.getByRole('checkbox',{name:'显示待核验地点'}).check()
  await expect(page.getByRole('checkbox',{name:'显示待核验地点'})).toBeChecked()
  const close=page.getByRole('button',{name:'关闭地图筛选'})
  if(await close.isVisible())await close.click()
  await page.getByRole('button',{name:'地图全屏',exact:true}).click()
  await expect(page.getByRole('button',{name:'退出地图全屏'})).toBeVisible()
  await page.getByRole('button',{name:'放大地图'}).click()
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('leonida-companion.map.v1')||'{}').zoom ?? -3)).toBeGreaterThanOrEqual(0.5)
  await expect.poll(()=>canvas.locator('img.leaflet-tile-loaded').count()).toBeGreaterThan(0)
  await page.getByRole('button',{name:'返回全图'}).click()
  await page.getByRole('button',{name:'退出地图全屏'}).click()
  await visit(page,'map?id=invalid-place')
  await expect(page.getByText('此地点链接无效或已移除。')).toBeVisible()
})

