test('地图底图、瓦片、缩放、点选、分类与无效分享地址',async({page,context},testInfo)=>{
  await visit(page,'map')
  const canvas=page.getByTestId('map-canvas')
  await expect(canvas).toBeVisible()
  await expect.poll(()=>canvas.locator('img.leaflet-image-layer').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(500)
  if(await page.getByRole('button',{name:'筛选',exact:true}).isVisible())await page.getByRole('button',{name:'筛选',exact:true}).click()
  await page.getByRole('button',{name:'收集品',exact:true}).click()
  await expect(page.getByRole('checkbox',{name:'显示待核验地点'})).not.toBeChecked()
  await page.getByRole('checkbox',{name:'显示待核验地点'}).check()
  await expect(page.getByRole('checkbox',{name:'显示待核验地点'})).toBeChecked()
  const close=page.getByRole('button',{name:'关闭地图筛选'})
  if(await close.isVisible())await close.click()
  await page.getByRole('button',{name:'地图全屏',exact:true}).click()
  await expect(page.getByRole('button',{name:'退出地图全屏'})).toBeVisible()
  const zoom = () => page.evaluate(()=>JSON.parse(localStorage.getItem('leonida-companion.map.v1')||'{}').zoom ?? -3.5)
  const initialZoom=await zoom()
  await page.getByRole('button',{name:'放大地图'}).click()
  await expect.poll(zoom).toBeGreaterThan(initialZoom)
  for(let steps=0;steps<3 && await zoom()<1;steps++){
    const before=await zoom()
    await page.getByRole('button',{name:'放大地图'}).click()
    await expect.poll(zoom).toBeGreaterThan(before)
  }
  await expect.poll(()=>canvas.locator('img.leaflet-tile-loaded').count()).toBeGreaterThan(0)
  const oldPosition=await page.evaluate(()=>JSON.parse(localStorage.getItem('leonida-companion.map.v1')||'{}').lng)
  const box=await canvas.boundingBox()
  expect(box).not.toBeNull()
  if(box){
    const point=(fraction:number)=>({x:box.x+box.width*fraction,y:box.y+box.height*.36})
    if(testInfo.project.name==='android'){
      const client=await context.newCDPSession(page)
      await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point(.23)]})
      for(const fraction of [.28,.34,.40,.45,.50]){
        await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[point(fraction)]})
      }
      await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
    }else{
      const start=point(.23)
      const end=point(.50)
      await page.mouse.move(start.x,start.y)
      await page.mouse.down()
      await page.mouse.move(end.x,end.y,{steps:9})
      await page.mouse.up()
    }
    await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('leonida-companion.map.v1')||'{}').lng)).not.toBe(oldPosition)
  }
  await page.getByRole('button',{name:'返回全图'}).click()
  await page.getByRole('button',{name:'退出地图全屏'}).click()
  await visit(page,'map?id=invalid-place')
  await expect(page.getByText('此地点链接无效或已移除。')).toBeVisible()
})

